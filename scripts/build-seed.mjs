// Turns the sample data in src/data into supabase/seed.sql, so the real
// database starts with exactly what demo mode shows.
// Run: npm run seed:sql   (then paste supabase/seed.sql into the SQL Editor)

import { writeFileSync } from 'node:fs';
import { colleges, fees } from '../src/data/colleges.js';
import { buildCutoffs } from '../src/data/cutoffs.js';

const q = (v) => (v == null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (list = []) => `array[${list.map(q).join(', ')}]::text[]`;
const collegeId = (slug) => `(select id from public.colleges where slug = ${q(slug)})`;

const lines = [
  '-- Sample data for the demo (generated by scripts/build-seed.mjs; do not edit by hand).',
  '-- Safe to re-run: existing rows are updated.',
  'begin;',
  '',
];

for (const c of colleges) {
  lines.push(
    `insert into public.colleges (slug, name, city, state, ownership, stream, university, established, seats, beds, avg_package_lpa, counselling, courses, image, summary, is_partner, is_published)
values (${[q(c.slug), q(c.name), q(c.city), q(c.state), q(c.ownership), q(c.stream), q(c.university), q(c.established), q(c.seats), q(c.beds), q(c.avg_package_lpa), arr(c.counselling), arr(c.courses), q(c.image), q(c.summary), c.is_partner, c.is_published].join(', ')})
on conflict (slug) do update set name = excluded.name, city = excluded.city, state = excluded.state, ownership = excluded.ownership, stream = excluded.stream,
  university = excluded.university, established = excluded.established, seats = excluded.seats, beds = excluded.beds, avg_package_lpa = excluded.avg_package_lpa,
  counselling = excluded.counselling, courses = excluded.courses, image = excluded.image, summary = excluded.summary,
  is_partner = excluded.is_partner, is_published = excluded.is_published;`
  );
}
lines.push('');

for (const f of fees) {
  lines.push(
    `insert into public.college_fees (college_id, course, academic_year, quota, tuition_per_year, hostel_per_year, one_time_fees, note, source_url)
values (${[collegeId(f.college_slug), q(f.course), q(f.academic_year), q(f.quota), q(f.tuition_per_year), q(f.hostel_per_year), q(f.one_time_fees), q(f.note), q(f.source_url)].join(', ')})
on conflict (college_id, course, quota, academic_year) do update set tuition_per_year = excluded.tuition_per_year,
  hostel_per_year = excluded.hostel_per_year, one_time_fees = excluded.one_time_fees, note = excluded.note, source_url = excluded.source_url;`
  );
}
lines.push('');

for (const c of colleges) {
  for (const row of buildCutoffs(c)) {
    lines.push(
      `insert into public.cutoffs (college_id, year, counselling, quota, category, round, closing_rank, closing_marks)
values (${[collegeId(c.slug), q(row.year), q(row.counselling), q(row.quota), q(row.category), q(row.round), q(row.closing_rank), q(row.closing_marks)].join(', ')})
on conflict (college_id, year, counselling, quota, category, round) do update set closing_rank = excluded.closing_rank, closing_marks = excluded.closing_marks;`
    );
  }
}

lines.push('', 'commit;', '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'));
console.log(`Wrote supabase/seed.sql: ${colleges.length} colleges, ${fees.length} fee rows.`);
